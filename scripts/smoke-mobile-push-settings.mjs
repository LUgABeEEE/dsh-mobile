const evidenceFlag = args.indexOf('--evidence-dir')
const evidenceDir = evidenceFlag >= 0 ? resolve(args[evidenceFlag + 1]) : process.env.DSH_PUSH_SETTINGS_EVIDENCE_DIR ?? null
if (args.includes('--help')) {
  console.log('Usage: node scripts/smoke-mobile-push-settings.mjs [--evidence-dir <dir>]\n' +
    'Optional: DSH_PUSH_SETTINGS_EVIDENCE_DIR or --evidence-dir retains screenshots and measured metrics.\n' +
    'Optional: DSH_PUSH_SETTINGS_REACT_DOM points at a react-dom package dir matching the repository React version.')
  process.exit(0)
}
const fail = (message) => { console.error(`push-settings fixture: ${message}`); process.exit(1) }

/** Locate the declared react-dom test dependency, verified against the repository React. */
async function resolveReactDom() {
  const reactVersion = require('react/package.json').version
  const candidates = []
  if (process.env.DSH_PUSH_SETTINGS_REACT_DOM) candidates.push(resolve(process.env.DSH_PUSH_SETTINGS_REACT_DOM))
  try { candidates.push(dirname(require.resolve('react-dom/package.json'))) } catch { /* not declared/installed */ }
  for (const candidate of candidates) {
    try {
      const manifest = require(join(candidate, 'package.json'))
      if (manifest.version === reactVersion && require.resolve(join(candidate, 'client.js'))) return candidate
    } catch { /* incompatible candidate */ }
  }
  return fail(`no react-dom ${reactVersion} declared/installed; run npm install (devDependencies include the matching react-dom) or set DSH_PUSH_SETTINGS_REACT_DOM`)
}

const reactDomDir = await resolveReactDom()
const reactDir = dirname(require.resolve('react/package.json'))
if (evidenceDir) await mkdir(evidenceDir, { recursive: true })

